/* PocketBase requires the CURRENT password to change it (min 8 chars for the new
   one). Other devices' existing tokens can still READ afterwards, but auth-refresh
   returns 401 — and since the app refreshes on every open, they are effectively
   signed out and will need the new password. */
function pbChangePassword(oldPw,newPw,confirmPw,cb){
  if(!oldPw||!newPw){cb(false,"Fill in every field.");return;}
  if(newPw.length<8){cb(false,"New password must be at least 8 characters.");return;}
  if(newPw!==confirmPw){cb(false,"The new passwords don’t match.");return;}
  if(newPw===oldPw){cb(false,"That’s the same as your current password.");return;}
  fetch(pbBase()+"/api/collections/users/records/"+pbUid(),{method:"PATCH",headers:pbHeaders(true),
    body:JSON.stringify({oldPassword:oldPw,password:newPw,passwordConfirm:confirmPw})})
    .then(function(r){return r.json().then(function(j){return r.ok?j:Promise.reject(j);});})
    .then(function(){
      /* re-authenticate so this device keeps a token minted against the new password */
      var c=pbCfg();
      pbLogin(pbEmail(),newPw,function(ok){cb(true,ok?null:"Password changed — please log in again.");},c.remember!==false);})
    .catch(function(j){
      var msg="Couldn’t change your password.";
      if(j&&j.data&&j.data.oldPassword)msg="Your current password isn’t right.";
      else if(j&&j.data&&j.data.password&&j.data.password.message)msg=j.data.password.message;
      else if(!j||!j.data)msg="Can’t reach the server. Is Tailscale on?";
      cb(false,msg);});}

/* silently extend the session on every open so a 90-day token never lapses mid-use */
function pbRefresh(cb){
  if(!syncOn()){cb&&cb(false);return;}
  fetch(pbBase()+"/api/collections/users/auth-refresh",{method:"POST",headers:pbHeaders(true)})
    .then(function(r){if(r.status===401||r.status===403)return Promise.reject("auth");if(!r.ok)return Promise.reject("error");return r.json();})
    .then(function(j){var c=pbCfg();c.token=j.token;c.uid=j.record.id;c.email=j.record.email;setPbCfg(c);cb&&cb(true);})
    .catch(function(e){
      if(e==="auth"){
        /* the session is dead (most often: the password was changed on another
           device). Drop the token but KEEP local data, and say why — the app
           otherwise appears signed in and then abruptly boots you. */
        pbClearSession(true);
        pbLoginState.err="Your session ended — that usually means the password was changed on another device. Please sign in again.";
        try{render();}catch(_e){}
      }
      cb&&cb(false);});}

