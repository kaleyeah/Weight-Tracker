/* Full logout: session AND this device's cached copy. Only for an explicit "Log out",
   where wiping is the point — a shared iPad must not leak the previous account, so
   the email is dropped too. */
var LOGOUT_JOURNAL_KEY="wl_logout_journal",LOGOUT_JOURNAL_V=1;
/* localStorage has no transaction, and a logout also has to clear a session that
   lives in a DIFFERENT store -- so genuine atomicity is not available. What is
   available is an honest record of how far the wipe got, so that an interrupted
   one is never resolved by guessing.

   Product Owner ruling 2026-08-01: when the app cannot tell whether a logout
   reached the committed state, it STOPS AND ASKS. It does not restore health
   data onto a device the athlete deliberately logged out of, and it does not
   finish destroying data they may not have exported. */
var logoutRecovery=null;   /* null, or {phase, journal} while a wipe is unresolved */
function logoutRecoveryPending(){return !!logoutRecovery;}
function logoutTargets(){return [KEY,TKEY,WOKEY,DIRTY_KEY,LAST_KEY,LASTOWNER_KEY,TRECOVERY_KEY];}
var LOGOUT_PHASES=["prepared","wiping","data-cleared","committed"];

function readSessionPair(){
  var out={local:null,session:null};
  try{out.local=localStorage.getItem(PB_KEY);}catch(e){}
  try{out.session=sessionStorage.getItem(PB_KEY);}catch(e){}
  return out;}

/* Exactly the approved keys, exactly the expected value types. restore() never
   iterates keys supplied by the file -- only the fixed target list -- so a
   tampered or corrupt journal cannot write anywhere it likes. */
function validLogoutJournal(j){
  if(!j||typeof j!=="object"||Array.isArray(j))return false;
  if(j.v!==LOGOUT_JOURNAL_V)return false;
  if(typeof j.account!=="string")return false;
  if(typeof j.appBuild!=="string"||!j.appBuild)return false;
  if(LOGOUT_PHASES.indexOf(j.phase)<0)return false;
  if(!j.vals||typeof j.vals!=="object"||Array.isArray(j.vals))return false;
  var want=logoutTargets(),i;
  if(Object.keys(j.vals).length!==want.length)return false;
  for(i=0;i<want.length;i++){
    if(!(want[i] in j.vals))return false;
    var v=j.vals[want[i]];
    if(!(v===null||typeof v==="string"))return false;}
  if(!j.session||typeof j.session!=="object")return false;
  if(!(j.session.local===null||typeof j.session.local==="string"))return false;
  if(!(j.session.session===null||typeof j.session.session==="string"))return false;
  return true;}

function readLogoutJournal(){
  var raw=null;
  try{raw=localStorage.getItem(LOGOUT_JOURNAL_KEY);}catch(e){return {status:"unreadable",j:null};}
  if(raw===null)return {status:"absent",j:null};
  var j=null;try{j=JSON.parse(raw);}catch(e){return {status:"invalid",j:null};}
  if(!validLogoutJournal(j))return {status:"invalid",j:null};
  return {status:"valid",j:j};}

function writeLogoutJournalPhase(j,phase){
  j.phase=phase;
  var str;
  try{str=JSON.stringify(j);}catch(e){return false;}
  try{localStorage.setItem(LOGOUT_JOURNAL_KEY,str);}catch(e){return false;}
  var back=null;
  try{back=localStorage.getItem(LOGOUT_JOURNAL_KEY);}catch(e){return false;}
  return back===str;}

function buildLogoutJournal(){
  var j={v:LOGOUT_JOURNAL_V,at:todayISO(),account:recoveryAccountId(),appBuild:APP_BUILD,
         phase:"prepared",vals:{},session:readSessionPair()};
  var ks=logoutTargets(),i;
  for(i=0;i<ks.length;i++){
    var v=null;
    try{v=localStorage.getItem(ks[i]);}catch(e){return null;}
    j.vals[ks[i]]=v;}
  return j;}

/* Restores the fixed target list AND both session stores, then verifies each. */
function restoreFromJournal(j){
  var ok=true,ks=logoutTargets(),i;
  for(i=0;i<ks.length;i++){
    var k=ks[i],want=j.vals[k];
    try{if(want===null)localStorage.removeItem(k);else localStorage.setItem(k,want);}catch(e){ok=false;continue;}
    var back=null;
    try{back=localStorage.getItem(k);}catch(e){ok=false;continue;}
    if(back!==want)ok=false;}
  [["local",localStorage],["session",typeof sessionStorage!=="undefined"?sessionStorage:null]].forEach(function(pair){
    var want=j.session[pair[0]],store=pair[1];
    if(!store)return;
    try{if(want===null)store.removeItem(PB_KEY);else store.setItem(PB_KEY,want);}catch(e){ok=false;return;}
    var back=null;
    try{back=store.getItem(PB_KEY);}catch(e){ok=false;return;}
    if(back!==want)ok=false;});
  return ok;}

function deleteLogoutJournalVerified(){
  try{localStorage.removeItem(LOGOUT_JOURNAL_KEY);}catch(e){return false;}
  var back=null;
  try{back=localStorage.getItem(LOGOUT_JOURNAL_KEY);}catch(e){return false;}
  return back===null;}

/* Boot gate. ANY surviving or unreadable journal stops the app before it loads
   user data or touches the network. Only the "prepared" phase is self-evidently
   safe: nothing had been removed yet, so the journal is simply discarded. */
function checkLogoutJournal(){
  var r=readLogoutJournal();
  if(r.status==="absent")return true;
  if(r.status==="valid"&&r.j.phase==="prepared"){
    if(deleteLogoutJournalVerified())return true;
    logoutRecovery={phase:"prepared",journal:r.j};return false;}
  logoutRecovery={phase:(r.status==="valid"?r.j.phase:"unreadable"),journal:(r.status==="valid"?r.j:null)};
  return false;}

/* The two answers the athlete can give. Neither is taken automatically. */
function logoutRecoveryRestore(){
  var j=logoutRecovery&&logoutRecovery.journal;
  if(!j){toast("That recovery record can't be read — nothing was changed");return false;}
  if(!restoreFromJournal(j)){toast("Couldn't fully restore — nothing else was changed");return false;}
  if(!deleteLogoutJournalVerified()){toast("Restored, but the recovery record could not be cleared");return false;}
  logoutRecovery=null;location.reload();return true;}
function logoutRecoveryFinish(){
  /* Product Owner ruling 2026-08-01: an UNREADABLE journal offers no destructive
     escape at all. The app cannot know what it would be erasing, so it stays
     locked and the bytes stay put until the reviewed recovery procedure. */
  if(!(logoutRecovery&&logoutRecovery.journal)){
    toast("This can't be erased from here — the record of the log-out can't be read");
    return false;}
  var ks=logoutTargets(),i;
  for(i=0;i<ks.length;i++){try{localStorage.removeItem(ks[i]);}catch(e){toast("Couldn't finish clearing this device — nothing more was changed");return false;}}
  /* Postcondition, verified: every target key absent, BOTH session slots absent
     entirely (not merely token-free -- ruling 8), and the journal gone. */
  for(i=0;i<ks.length;i++){
    var still=null;
    try{still=localStorage.getItem(ks[i]);}catch(e){toast("Couldn't verify this device was cleared");return false;}
    if(still!==null){toast("Couldn't finish clearing this device");return false;}}
  try{pbClearSession(false);}catch(e){}
  try{sessionStorage.removeItem(PB_KEY);}catch(e){}
  /* Same postcondition as an ordinary logout: pbClearSession legitimately keeps
     the server URL (configuration, not session) in the localStorage slot, so
     that slot is checked for CREDENTIALS; sessionStorage must be entirely empty
     of the key. */
  var lraw2=null;
  try{lraw2=localStorage.getItem(PB_KEY);}catch(e){toast("Couldn't verify the session was cleared");return false;}
  if(lraw2!==null){
    var lc2=null;try{lc2=JSON.parse(lraw2);}catch(e){toast("Couldn't clear the session");return false;}
    if(lc2&&(lc2.token||lc2.uid||lc2.email)){toast("Couldn't clear the session");return false;}}
  try{if(sessionStorage.getItem(PB_KEY)!==null){toast("Couldn't clear the session");return false;}}
  catch(e){toast("Couldn't verify the session was cleared");return false;}
  if(!deleteLogoutJournalVerified()){toast("Couldn't clear the recovery record");return false;}
  logoutRecovery=null;location.reload();return true;}

function pbForceLogout(){
  if(ownershipAmbiguous()){
    toast("Can't log out yet — this device holds data from another account");
    return false;}
  var j=buildLogoutJournal();
  if(!j||!writeLogoutJournalPhase(j,"prepared")){
    toast("Couldn't prepare a safe log-out on this device — nothing was removed");
    return false;}

  function rollback(msg){
    if(restoreFromJournal(j)&&deleteLogoutJournalVerified()){
      toast(msg+" — every value was put back exactly as it was");
    }else{
      logoutRecovery={phase:j.phase,journal:j};
      toast(msg+". This device now needs a decision before it can be used.");}
    return false;}

  if(!writeLogoutJournalPhase(j,"wiping"))return rollback("Couldn't record the log-out safely");

  var acct=recoveryAccountId();
  if(!clearTrainingRecovery(acct))return rollback("Couldn't clear this device's saved training copy");

  var targets=logoutTargets(),i;
  for(i=0;i<targets.length;i++){
    try{localStorage.removeItem(targets[i]);}catch(e){return rollback("Couldn't clear this device");}}
  for(i=0;i<targets.length;i++){
    var still=null;
    try{still=localStorage.getItem(targets[i]);}catch(e){return rollback("Couldn't verify this device was cleared");}
    if(still!==null)return rollback("Couldn't clear this device");}

  if(!writeLogoutJournalPhase(j,"data-cleared"))return rollback("Couldn't record the log-out safely");

  pbClearSession(false);
  try{sessionStorage.removeItem(PB_KEY);}catch(e){}
  /* The privacy postcondition is ABSENCE of wl_pb in both stores, not merely the
     absence of a parseable token: malformed session bytes are still session
     bytes. pbClearSession keeps base/remember in localStorage by design, so that
     slot is checked for credentials only after re-writing; sessionStorage must be
     entirely empty of the key. */
  var leftover=false;
  var lraw=null;try{lraw=localStorage.getItem(PB_KEY);}catch(e){leftover=true;}
  if(lraw!==null&&lraw!==undefined&&lraw!==""){
    var lc=null;try{lc=JSON.parse(lraw);}catch(e){leftover=true;}
    if(lc&&(lc.token||lc.uid||lc.email))leftover=true;}
  try{if(sessionStorage.getItem(PB_KEY)!==null)leftover=true;}catch(e){leftover=true;}
  if(leftover)return rollback("Couldn't clear the session");

  if(!writeLogoutJournalPhase(j,"committed")){
    /* The wipe is done and the session is gone; only the record of it failed.
       Leave it: boot will stop and ask rather than silently undo a completed
       logout or silently keep a copy of the data. */
    logoutRecovery={phase:"committed",journal:j};
    toast("Logged out, but this device needs a decision before it can be used again.");
    return false;}
  /* Verified deletion. A surviving journal holds a complete copy of the health
     data this logout just erased, so an unverified removeItem is not enough. */
  if(!deleteLogoutJournalVerified()){
    logoutRecovery={phase:"committed",journal:j};
    toast("Logged out, but a copy of the cleared data is still on this device.");
    return false;}
  return true;}
