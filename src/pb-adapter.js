function pbSave(fields,cb){
  /* Enforced at the primitive, not at named callers. pbSave has call sites in
     the HealthKit import, the coach request, the nightly generator and
     pushDataPromise() as well as cloudPush/trainingPush; gating those by name
     would leave whichever one is added next unprotected. */
  if(ownershipAmbiguous()){cb&&cb(false,"ambiguous");return;}
  if(!syncOn()){cb&&cb(false,"not configured");return;}
  var base=pbBase();
  function write(id){
    var url=base+"/api/collections/appdata/records"+(id?("/"+id):"");
    var body=id?fields:Object.assign({user:pbUid()},fields);
    return fetch(url,{method:id?"PATCH":"POST",headers:pbHeaders(true),body:JSON.stringify(body)})
      .then(function(r){
        if(r.status===401||r.status===403)return Promise.reject("auth");
        if(r.status===404&&id){pbRecId=null;return Promise.reject("gone");}
        if(!r.ok)return Promise.reject("error");
        return r.json();});}
  var run=pbRecId?write(pbRecId):new Promise(function(res,rej){
    pbGetRecord(function(rec,err){if(err)return rej(err);write(rec?rec.id:null).then(res,rej);});});
  run.then(function(j){if(j&&j.id)pbRecId=j.id;cb&&cb(true,null);})
     .catch(function(e){
       if(e==="gone"){pbSave(fields,cb);return;}
       cb&&cb(false,(e==="auth")?"auth":(e==="error")?"error":"offline");});}

